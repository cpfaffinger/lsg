/**
 * Difficulty tuner: for every campaign level, binary-searches the highest difficulty at which
 * three competent bot variants all win while keeping a target share of their squad. Writes apps/game/src/data/levels/tuning.ts.
 *
 *   node tools/balance/tune.ts [--dry]
 */
import fs from 'node:fs';
import path from 'node:path';
import { CAMPAIGN_LENGTH, campaignLevel, expectedLoadout } from '../../apps/game/src/data/levels/campaign.ts';
import { DEFAULT_MODIFIERS } from '../../apps/game/src/sim/types.ts';
import { playLevel } from './bot.ts';

const dry = process.argv.includes('--dry');

/** Share of the peak squad a competent player should still have at the end. Lower = harder. */
function targetSurvival(level: number): number {
  return 0.7 - ((level - 1) / (CAMPAIGN_LENGTH - 1)) * 0.35;
}

/** Three competent players with different reaction distances; all of them must pass. */
const VARIANTS = [12, 18, 26];

function passes(level: number, difficulty: number): { ok: boolean; survival: number } {
  const loadout = expectedLoadout(level);
  const modifiers = { ...DEFAULT_MODIFIERS, startUnits: loadout.startUnits, damageMultiplier: loadout.power };
  const def = campaignLevel(level, difficulty);
  let worst = 1;
  for (const lookahead of VARIANTS) {
    const run = playLevel(def, modifiers, 'good', lookahead);
    const survival = run.status === 'won' ? run.units / Math.max(1, run.stats.peakUnits) : 0;
    worst = Math.min(worst, survival);
  }
  return { ok: worst >= targetSurvival(level), survival: worst };
}

const results: number[] = [];
for (let level = 1; level <= CAMPAIGN_LENGTH; level++) {
  let lo = 0.03;
  let hi = 1.2;
  if (!passes(level, lo).ok) {
    console.warn(`level ${level}: not winnable even at difficulty ${lo}`);
  }
  for (let i = 0; i < 10; i++) {
    const mid = (lo + hi) / 2;
    if (passes(level, mid).ok) lo = mid;
    else hi = mid;
  }
  // Outcomes are not perfectly monotonic, so step down until the value and a margin below
  // it both pass.
  let value = Number((lo * 0.92).toFixed(3));
  for (const factor of [0.92, 0.85, 0.78, 0.7, 0.6, 0.5, 0.4, 0.3]) {
    value = Number((lo * factor).toFixed(3));
    if (passes(level, value).ok && passes(level, value * 0.9).ok) break;
  }
  const check = passes(level, value);
  results.push(value);
  console.info(
    `level ${String(level).padStart(2)}: difficulty ${value.toFixed(3)} survival ${check.survival.toFixed(2)} ${check.ok ? '' : '(edge)'}`,
  );
}

if (!dry) {
  const file = path.resolve('apps/game/src/data/levels/tuning.ts');
  const body = `// Generated by tools/balance/tune.ts. Do not edit by hand; rerun the tuner instead.
/** Wave/boss difficulty per campaign level (index 0 = level 1). */
export const CAMPAIGN_DIFFICULTY: readonly number[] = [
${results.map((v, i) => `  ${v}, // level ${i + 1}`).join('\n')}
];
`;
  fs.writeFileSync(file, body);
  console.info(`wrote ${file}`);
}
